export const SUPPORTED_LOCALES = ['zh', 'en'] as const
export type Locale = (typeof SUPPORTED_LOCALES)[number]

function initialLocale(): Locale {
  if (typeof localStorage === 'undefined') return 'zh'
  const saved = localStorage.getItem('locale')
  return saved === 'en' ? 'en' : 'zh'
}

export const i18n = createI18n({
  legacy: false,
  locale: initialLocale(),
  fallbackLocale: 'zh',
  messages,
})

/** 同步 <html lang> 到当前语言(无障碍/断词/屏读正确性) */
export function applyDocumentLang(locale: Locale) {
  if (typeof document !== 'undefined') {
    document.documentElement.lang = locale === 'en' ? 'en' : 'zh-CN'
  }
}

applyDocumentLang(initialLocale())

/** 切换语言并持久化 */
export function setLocale(locale: Locale) {
  ;(i18n.global.locale as unknown as { value: Locale }).value = locale
  if (typeof localStorage !== 'undefined') localStorage.setItem('locale', locale)
  applyDocumentLang(locale)
}
